"""Typed access to SQLite rows: the only place where untyped rows are read."""

import sqlite3
from collections.abc import Callable, Generator, Sequence
from contextlib import contextmanager
from dataclasses import dataclass
from datetime import date, datetime

from meute.core.actor import Actor, Author, Channel
from meute.core.errors import NotFound
from meute.core.instants import from_db, to_db
from meute.core.project import Project, ProjectId, ProjectRef, RepoId
from meute.core.status import Priority, StatusKind, TaskStatus, status_from_kind
from meute.core.task import Due, DueAt, DueDate, Note, Task, TaskEvent, TaskId, task_label

TASK_SELECT = """
SELECT t.id, t.title, t.description, t.status, t.blocked_reason, t.priority,
       t.due_date, t.due_at, t.project_id, p.name, t.repo_id, t.version,
       t.created_at, t.updated_at, t.completed_at
FROM tasks t LEFT JOIN projects p ON p.id = t.project_id
"""

PROJECT_SELECT = "SELECT id, name, description, instructions, created_at FROM projects"


def fetch_one(
    conn: sqlite3.Connection, sql: str, params: Sequence[object] = ()
) -> tuple[object, ...] | None:
    """Run `sql` and return its first row, or None."""
    row: tuple[object, ...] | None = conn.execute(sql, params).fetchone()  # pyright: ignore[reportAny] — sqlite3 rows are untyped
    return row


def fetch_all(
    conn: sqlite3.Connection, sql: str, params: Sequence[object] = ()
) -> list[tuple[object, ...]]:
    """Run `sql` and return all its rows."""
    return [tuple(row) for row in conn.execute(sql, params)]  # pyright: ignore[reportAny] — sqlite3 rows are untyped


def _text(value: object) -> str:
    if not isinstance(value, str):
        message = f"corrupt row: expected text, got {value!r}"
        raise ValueError(message)  # noqa: TRY004 — a corrupt database, not a caller error
    return value


def as_integer(value: object) -> int:
    """Return `value` as an int (not a bool); a corrupt database raises ValueError."""
    if isinstance(value, bool) or not isinstance(value, int):
        message = f"corrupt row: expected integer, got {value!r}"
        raise ValueError(message)  # noqa: TRY004 — a corrupt database, not a caller error
    return value


def inserted_id(cursor: sqlite3.Cursor) -> int:
    """Return the row id generated by the INSERT run on `cursor`."""
    if cursor.lastrowid is None:
        message = "INSERT returned no row id"
        raise RuntimeError(message)
    return cursor.lastrowid


def _instant(value: object) -> datetime:
    return from_db(_text(value))


def _optional[T](convert: Callable[[object], T], value: object) -> T | None:
    return None if value is None else convert(value)


def row_to_project(row: tuple[object, ...]) -> Project:
    """Convert a `projects` row (id, name, description, instructions, created_at)."""
    return Project(
        id=ProjectId(as_integer(row[0])),
        name=_text(row[1]),
        description=_text(row[2]),
        instructions=_text(row[3]),
        created_at=_instant(row[4]),
    )


def _row_due(due_date: object, due_at: object) -> Due | None:
    if due_date is not None:
        return DueDate(day=date.fromisoformat(_text(due_date)))
    if due_at is not None:
        return DueAt(at=_instant(due_at))
    return None


def row_to_task(row: tuple[object, ...]) -> Task:
    """Convert a row of `TASK_SELECT` into a task.

    Raises:
        ValueError: the row holds an unknown status or priority, or a wrong type.
    """
    project_id = _optional(as_integer, row[8])
    project = (
        None if project_id is None else ProjectRef(id=ProjectId(project_id), name=_text(row[9]))
    )
    repo_id = _optional(as_integer, row[10])
    status: TaskStatus = status_from_kind(StatusKind(_text(row[3])), _optional(_text, row[4]))
    return Task(
        id=TaskId(as_integer(row[0])),
        title=_text(row[1]),
        description=_text(row[2]),
        status=status,
        priority=Priority(_text(row[5])),
        due=_row_due(row[6], row[7]),
        project=project,
        repo_id=None if repo_id is None else RepoId(repo_id),
        version=as_integer(row[11]),
        created_at=_instant(row[12]),
        updated_at=_instant(row[13]),
        completed_at=_optional(_instant, row[14]),
    )


def row_to_event(row: tuple[object, ...]) -> TaskEvent:
    """Convert a `task_events` row (task_id, field, old, new, author, channel, session, at)."""
    return TaskEvent(
        task_id=TaskId(as_integer(row[0])),
        field=_text(row[1]),
        old_value=_optional(_text, row[2]),
        new_value=_optional(_text, row[3]),
        author=Author(_text(row[4])),
        channel=Channel(_text(row[5])),
        session_id=_optional(_text, row[6]),
        created_at=_instant(row[7]),
    )


def row_to_note(row: tuple[object, ...]) -> Note:
    """Convert a `task_notes` row (id, task_id, body, author, channel, session, at)."""
    return Note(
        id=as_integer(row[0]),
        task_id=TaskId(as_integer(row[1])),
        body=_text(row[2]),
        author=Author(_text(row[3])),
        channel=Channel(_text(row[4])),
        session_id=_optional(_text, row[5]),
        created_at=_instant(row[6]),
    )


def fetch_task(conn: sqlite3.Connection, task_id: TaskId) -> Task:
    """Return the task `task_id`.

    Raises:
        NotFound: no such task.
    """
    row = fetch_one(conn, f"{TASK_SELECT} WHERE t.id = ?", (task_id,))
    if row is None:
        entity = "task"
        raise NotFound(entity, task_label(task_id))
    return row_to_task(row)


@dataclass(frozen=True, slots=True, kw_only=True)
class EventRecord:
    """A change to record in the history of a task."""

    task_id: TaskId
    field: str
    old_value: str | None
    new_value: str | None
    actor: Actor
    at: datetime


def insert_event(conn: sqlite3.Connection, event: EventRecord) -> None:
    """Append `event` to the history."""
    conn.execute(
        "INSERT INTO task_events (task_id, field, old_value, new_value, author, channel,"
        " session_id, created_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
        (
            event.task_id,
            event.field,
            event.old_value,
            event.new_value,
            event.actor.author.value,
            event.actor.channel.value,
            event.actor.session_id,
            to_db(event.at),
        ),
    )


def due_columns(due: Due | None) -> tuple[str | None, str | None]:
    """Return the `(due_date, due_at)` column values for `due`."""
    match due:
        case None:
            return None, None
        case DueDate():
            return due.day.isoformat(), None
        case DueAt():
            return None, to_db(due.at)


@contextmanager
def project_must_exist(project_id: ProjectId | None) -> Generator[None]:
    """Turn a foreign-key violation raised in the block into `NotFound` for the project."""
    try:
        yield
    except sqlite3.IntegrityError as error:
        if error.sqlite_errorname == "SQLITE_CONSTRAINT_FOREIGNKEY":
            entity = "project"
            raise NotFound(entity, str(project_id)) from error
        raise
