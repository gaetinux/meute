"""Generated tmux configuration of the `meute` server."""

from dataclasses import dataclass

from meute.tmux.names import MAIN_TARGET, STATUS_OPTION
from meute.tmux.quote import format_literal

_SYNC_HOOKS = ("client-attached", "client-resized")


@dataclass(frozen=True, slots=True, kw_only=True)
class Keys:
    """Key bindings installed by meute, as tmux key names such as `M-p`."""

    focus_board: str
    focus_main: str
    next_attention: str = "M-n"
    previous_attention: str = "M-N"
    detach: str = "M-q"
    quick_task: str = "M-t"


@dataclass(frozen=True, slots=True, kw_only=True)
class LayoutSpec:
    """Everything needed to build and render the `meute` layout."""

    board_width: int
    narrow_threshold: int
    board_command: tuple[str, ...]
    welcome_command: tuple[str, ...]
    sync_command: tuple[str, ...]
    keys: Keys
    attention_command: tuple[str, ...] = ()  # meute itself, for the keys that run it


def _sh_quote(word: str) -> str:
    """Quote a word for `sh` with single quotes."""
    return "'" + word.replace("'", "'\\''") + "'"


def _tmux_escape(text: str) -> str:
    """Escape text for a double-quoted tmux string."""
    return "".join("\\" + c if c in '\\"$' else c for c in text)


_INTERFACE = (
    "set -g mouse on",
    'set -g status-left ""',
    f'set -g status-right "#{{{STATUS_OPTION}}}"',
    "set -g status-right-length 120",
    'set -g status-style "bg=default,fg=colour245"',
    'set -g window-status-format ""',
    'set -g window-status-current-format ""',
    "set -g pane-border-lines single",
    'set -g pane-border-style "fg=colour238"',
    'set -g pane-active-border-style "fg=colour238"',
    # Where the focus is: the board dims itself (focus events), tmux greys the other pane.
    "set -g focus-events on",
    'set -g window-style "bg=colour234"',
    'set -g window-active-style "default"',
    "set -g visual-activity off",
    "set -g visual-bell off",
    "set -g visual-silence off",
    "set -g bell-action none",
    "set -g display-time 1000",
)


_POPUP_WIDTH = 76
_POPUP_HEIGHT = 12


def _shell_string(command: tuple[str, ...]) -> str:
    """Return `command` as a double-quoted tmux string holding an `sh` command line."""
    return '"' + _tmux_escape(" ".join(_sh_quote(word) for word in command)) + '"'


def _run_shell(command: tuple[str, ...]) -> str:
    """Return a `run-shell -b` command line for `command`, quoted for `sh` and for tmux.

    `run-shell` expands formats: each `#` is doubled so that it stays literal.
    """
    return f"run-shell -b {format_literal(_shell_string(command))}"


def quick_task_command(meute: tuple[str, ...]) -> tuple[str, ...]:
    """Return the command of the quick task window, from the command that starts meute."""
    return (*meute, "task", "quick")


def _quick_task_binding(spec: LayoutSpec) -> tuple[str, ...]:
    """Bind the quick task window, as wide as the client allows (tmux refuses a wider one).

    `display-popup` expands no format in its command, so its `#` stay single; each command
    of the `if-shell` is parsed once more when the key is pressed, hence the second escape.
    """
    # Inside if-shell strings, a flag unknown to an old tmux fails only when the key is pressed.
    if not spec.attention_command:
        return ()
    command = _shell_string(quick_task_command(spec.attention_command))
    narrow, wide = (
        _tmux_escape(f"display-popup -B -E -w {width} -h {_POPUP_HEIGHT} {command}")
        for width in ("100%", _POPUP_WIDTH)
    )
    condition = f"#{{e|<:#{{client_width}},{_POPUP_WIDTH}}}"
    return (f'bind -n {spec.keys.quick_task} if-shell -F "{condition}" "{narrow}" "{wide}"',)


def _attention_bindings(spec: LayoutSpec) -> tuple[str, ...]:
    if not spec.attention_command:
        return ()
    keys = spec.keys
    return tuple(
        f"bind -n {key} {_run_shell((*spec.attention_command, 'session', direction))}"
        for key, direction in ((keys.next_attention, "next"), (keys.previous_attention, "previous"))
    )


def render_config(spec: LayoutSpec) -> str:
    """Render the tmux configuration file of the `meute` server.

    Each command run by tmux is quoted for `sh`, its `#` doubled so that `run-shell` does
    not expand it as a format, then escaped twice for a tmux string when it sits in a hook:
    tmux parses it when the file is sourced and again when the hook runs.
    """
    target = MAIN_TARGET
    hook = _tmux_escape(_run_shell(spec.sync_command))
    lines = [
        "# Generated by meute: rewritten at every launch, do not edit.",
        *_INTERFACE,
        *_attention_bindings(spec),
        *_quick_task_binding(spec),
        f"bind -n {spec.keys.detach} detach-client",
        (
            f"bind -n {spec.keys.focus_board} switch-client -t {target}"
            f" \\; select-pane -t '{target}.{{right}}'"
        ),
        # Narrow mode (zoomed window): the board is all there is, so the key does nothing.
        (
            f'bind -n {spec.keys.focus_main} if-shell -F "#{{window_zoomed_flag}}" ""'
            f" \"select-pane -t '{target}.{{left}}'\""
        ),
        *(f'set-hook -g {name} "{hook}"' for name in _SYNC_HOOKS),
    ]
    return "\n".join(lines) + "\n"
