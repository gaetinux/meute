"""Generated tmux configuration of the `meute` server."""

from dataclasses import dataclass

from meute.tmux.names import MAIN_TARGET, STATUS_OPTION

_SYNC_HOOKS = ("client-attached", "client-resized")


@dataclass(frozen=True, slots=True, kw_only=True)
class Keys:
    """Key bindings installed by meute, as tmux key names such as `M-p`."""

    focus_board: str
    focus_main: str


@dataclass(frozen=True, slots=True, kw_only=True)
class LayoutSpec:
    """Everything needed to build and render the `meute` layout."""

    board_width: int
    narrow_threshold: int
    board_command: tuple[str, ...]
    welcome_command: tuple[str, ...]
    sync_command: tuple[str, ...]
    keys: Keys


def _sh_quote(word: str) -> str:
    """Quote a word for `sh` with single quotes."""
    return "'" + word.replace("'", "'\\''") + "'"


def _tmux_escape(text: str) -> str:
    """Escape text for a double-quoted tmux string."""
    return "".join("\\" + c if c in '\\"$' else c for c in text)


def render_config(spec: LayoutSpec) -> str:
    """Render the tmux configuration file of the `meute` server.

    The sync command is quoted for `sh`, then escaped twice for a tmux string:
    tmux parses it when the file is sourced and again when the hook runs.
    """
    target = MAIN_TARGET
    shell = " ".join(_sh_quote(word) for word in spec.sync_command)
    run_shell = f'run-shell -b "{_tmux_escape(shell)}"'
    hook = _tmux_escape(run_shell)
    lines = [
        "# Generated by meute: rewritten at every launch, do not edit.",
        'set -g status-left "[meute] "',
        f'set -g status-right "#{{{STATUS_OPTION}}}"',
        "set -g status-right-length 80",
        (
            f"bind -n {spec.keys.focus_board} switch-client -t {target}"
            f" \\; select-pane -t '{target}.{{right}}'"
        ),
        f"bind -n {spec.keys.focus_main} select-pane -t '{target}.{{left}}'",
        *(f'set-hook -g {name} "{hook}"' for name in _SYNC_HOOKS),
    ]
    return "\n".join(lines) + "\n"
